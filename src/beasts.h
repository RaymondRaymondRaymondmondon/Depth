struct Den { int tx = 0, ty = 0; Vector2 pos{0, 0}; float repopT = 0; };
struct SoundEvent { Vector2 pos{0, 0}; float intensity = 0, life = 0; int source = -1; };
struct InkPuff { Vector2 pos{0, 0}; float life = 0, r = 60, max = 2.6f; int kind = 0; }; // a blinding cloud: 0 ink, 1 spores, 2 powder smoke
struct BeastLight { Vector2 pos{0, 0}; float r = 0, strength = 0; };                  // a light beasts can see by, rebuilt every tick
struct BeastProp { Vector2 pos{0, 0}, vel{0, 0}; float t = 0; int kind = 0, owner = -1; }; // a biome object: a fused powder keg, a falling coconut

// A downsampled scalar field that spreads (diffusion), fades (decay) and drifts (a constant current). Solid
// tiles don't carry scent. Beasts read its gradient to follow a trail uphill toward its source.
struct ScentGrid {
    int w = 0, h = 0;
    float cell = 32, diffusion = 6.0f, decay = 0.06f;
    Vector2 drift{0, 0};
    std::vector<float> blood, trail, tmp;
    void Init(int cw, int chh, float cellPx);
    void Emit(std::vector<float>& ch, Vector2 at, float amount);
    void Step(float dt, const std::vector<uint8_t>& solidCells);
    float Sample(const std::vector<float>& ch, Vector2 at) const;
    Vector2 Gradient(const std::vector<float>& ch, Vector2 at) const;
};

// The level as the creatures see it: which tiles are solid, which are dangerous, and A* over them.
struct NavGrid {
    int w = 0, h = 0;
    float tile = 32;
    std::vector<uint8_t> solid, hazard;
    mutable std::vector<float> g;
    mutable std::vector<int> parent;
    mutable std::vector<uint32_t> stamp;
    mutable uint32_t curStamp = 0;
    bool Solid(int x, int y) const { return x < 0 || x >= w || (y >= 0 && y < h && solid[y * w + x]); }
    bool Open(int x, int y) const { return x >= 0 && x < w && y >= 0 && y < h && !solid[y * w + x]; }
    bool Standable(int x, int y) const { return Open(x, y) && Solid(x, y + 1); }
    bool Hazard(int x, int y) const { return x >= 0 && x < w && y >= 0 && y < h && hazard[y * w + x]; }
    bool LineOfSight(Vector2 a, Vector2 b) const;
    int FloorBelow(int x, int y) const; // the first solid row at or below y (h if none)
    bool FindPath(MoveMode m, Vector2 from, Vector2 to, std::vector<Vector2>& out, int maxExpand) const;
};

struct BeastWorld {
    int biome = -1;
    bool active = false;
    std::vector<Beast> beasts;
    std::vector<Den> dens;
    std::vector<SoundEvent> sounds;
    std::vector<InkPuff> ink;
    std::vector<BeastLight> lights;   // this tick's flashes, lamps and glow
    std::vector<Vector2> lamps;       // the level's fixed light pools ('o')
    std::vector<BeastProp> props;
    std::vector<int> dynamic;         // cells that can change at runtime (fragile scaffolding), re-checked every tick
    ScentGrid scent;
    NavGrid nav;
    float time = 0, scentT = 0, repopT = 0, noiseT = 0;
    float limitX = 1e9f;          // creatures stay out of a boss arena appended past this x
    int nextId = 1, replansLeft = 0;
    unsigned seed = 1, rng = 1;
    int kills = 0, scavenged = 0, births = 0, hides = 0, abnormals = 0; // running tallies, read by --verify-beasts
    int deaths[4] = {0, 0, 0, 0}; // how they died: eaten or killed by a beast, a hazard, the sea, a shot or blast
    // the runtime director (ParkourReference1.3's apex beasts): not a script - it only decides when an apex may roam in
    float calmT = 0, apexT = 0, tension = 0;
    Vector2 apexPos{-1e9f, -1e9f}; // where the apex is this tick (its shadow darkens everything under it)
    int apexVisits = 0;
};

