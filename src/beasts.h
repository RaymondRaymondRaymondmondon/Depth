// ============================================================================
//  DEPTH - living creature AI for the parkour levels (ParkourReference1.2.pdf, "Advanced Beast AI").
//
//  Every beast runs the reference's four-tier pipeline each tick:
//    1. senses    - a sight cone with a real line-of-sight raycast through the tiles, hearing that falls off
//                   with distance (I / (1 + k d^2)), and smell read off a diffusing scent grid (blood, the
//                   diver's trail); what it notices goes into a short decaying memory, so a predator keeps
//                   hunting where it last saw you after you break line of sight
//    2. drives    - hunger, fear, fatigue, carried between ticks
//    3. utility   - sigmoid response curves score Hunt / Flee / Scavenge / Rest / Investigate / Explore /
//                   Wander (plus species extras); the best wins, with hysteresis so it doesn't dither
//    4. motor     - an A* route across the level (walkers on floor spans with steps, drops and hops;
//                   swimmers and fliers through open water/air), then physics: acceleration, drag, gravity
//                   for walkers, tile collision
//  Personalities: aggression, bravery, energy, curiosity, plus intelligence (a dim beast forgets fast, never
//  leads its target and steers greedily) and wanderlust (roams far from its den and migrates). About 15%
//  roll one of the reference's 12 abnormal profiles, which override the utility choice.
//  Dens are generated by the level (tile 'D'): prey flee to them, beasts rest in them, and the population
//  comes back out of them after something dies.
//
//  This file holds the engine; each biome supplies a species table and a food web (see beasts.cpp).
// ============================================================================
